// Copies a grid into ArrGrid / ArrWeight.
// Note: grid is [y][x] (rows first), the arrays are [x][y].
export function LoadGrid(grid: string[]): void {
  for (let y = 0; y < GridArr_Y; y++) {
    for (let x = 0; x < GridArr_X; x++) {
      const ch = grid[y][x]
      ArrGrid[x][y] = ch === '#'
      ArrWeight[x][y] = ch === 'w' ? 5 : 1
    }
  }
}
